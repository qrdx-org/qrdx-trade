/**
 * The trade site's Worker: the Next.js app (built by the OpenNext adapter into .open-next/)
 * and the site's stateful services (relay/), in one Worker on trade.qrdx.org:
 *
 *  - /api/relay/*     QRDX Connect relay (docs/CONNECT.md), a Durable Object per session;
 *  - /api/history/*   market history (ARCHITECTURE.md §12), recorded by the cron below;
 *  - /api/profiles/*  public profiles and the NFT market registry (docs/PROFILES.md).
 *
 * Everything else is the Next.js app. The app's server code reaches the services through the
 * WORKER_SELF_REFERENCE binding (lib/server/relay-service.ts): a Worker cannot fetch() its
 * own routes over the network.
 */

// @ts-ignore: generated by `opennextjs-cloudflare build`, bundled by wrangler
import nextApp from './.open-next/worker.js'
import relay, { MarketHistory, Profiles, RelaySession, type Env as RelayEnv } from './relay/src/worker'

export { MarketHistory, Profiles, RelaySession }

const SERVICES = /^\/api\/(relay|history|profiles)(\/|$)/

export default {
  async fetch(req: Request, env: RelayEnv, ctx: ExecutionContext): Promise<Response> {
    if (SERVICES.test(new URL(req.url).pathname)) return relay.fetch(req, env)
    return (nextApp as ExportedHandler<RelayEnv>).fetch!(req as never, env, ctx)
  },

  /** Every minute: record each network's pools (market history). */
  scheduled: relay.scheduled,
} satisfies ExportedHandler<RelayEnv>
